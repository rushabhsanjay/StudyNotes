"""
Clipboard (ChatGPT / Gemini / Claude markdown)
    -> formatted DOCX (academic / journal style)
    -> optionally a companion HTML page (via 04_FORMAT_TEXT_TO_HTML.py)

What this version handles that the old one did not
--------------------------------------------------
* LaTeX math  \\( .. \\)            -> native Word equation (inline)
              \\[ .. \\] / $$ .. $$  -> native Word equation (display, centred)
  Uses latex2mathml + Microsoft's MML2OMML.XSL. If either is missing it
  degrades to readable Unicode text instead of crashing.
* ChatGPT image cards  [title](https://images.openai.com/...)  and the
  stray "6" / "9" image-count lines they leave behind are stripped.
* Numbered lists keep the numbers written in the markdown (no more
  "all lists continue from 1" Word numbering weirdness).
* Table header rows repeat across page breaks; tables are 100% wide.

Destination resolution
----------------------
The VBA passes the destination folder and file stem via a scratch text
file (ARGS_FILE) rather than as command-line arguments, because cmd.exe
mangles quoted paths that end in a backslash. Priority order:

    1. command-line:  python 02_FORMAT_TEXT_TO_DOCX.py <out_dir> <base_name>
    2. ARGS_FILE:     two lines, folder then file stem (VBA)
    3. OUT_FILE:      fixed fallback path configured below

When a folder + stem are supplied, a companion HTML page is generated by
calling 04_FORMAT_TEXT_TO_HTML.py with the same two values.

Install:
    pip install pyperclip python-docx latex2mathml lxml
    # optional, for the HTML companion:
    pip install markdown
"""

