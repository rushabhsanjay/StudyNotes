IMG_LINE = re.compile(r'^\s*!?\[[^\]]*\]\(https?://images\.openai\.com/[^)]*\)\s*$')
IMG_LINK = re.compile(r'!?\[[^\]]*\]\(https?://images\.openai\.com/[^)]*\)')


def clean_markdown(text):
    """Strip ChatGPT image cards, their stray counters, and image links."""
    lines = text.replace('\r\n', '\n').replace('\r', '\n').split('\n')
    out, in_code, gap = [], False, 99

    for ln in lines:
        s = ln.strip()

        if s.startswith('```'):
            in_code = not in_code
            out.append(ln); gap = 99
            continue

        if in_code:
            out.append(ln)
            continue

        if IMG_LINE.match(ln):
            gap = 0
            continue

        if s == '':
            out.append(ln)
            gap += 1
            continue

        if (STRIP_LONE_DIGITS and gap <= 3
                and re.fullmatch(r'\d{1,3}', s)):
            gap += 1
            continue

        gap = 99
        out.append(ln)

    t = '\n'.join(out)
    t = IMG_LINK.sub('', t)
    t = re.sub(r'[ \t]+\n', '\n', t)
    t = re.sub(r'\n{3,}', '\n\n', t)
    return t.strip() + '\n'


