def configure_styles(doc):
    normal = doc.styles['Normal']
    normal.font.name = BODY_FONT
    normal.font.size = BODY_SIZE
    normal.font.color.rgb = INK
    pf = normal.paragraph_format
    pf.alignment    = WD_ALIGN_PARAGRAPH.JUSTIFY
    pf.line_spacing = 1.15
    pf.space_after  = Pt(6)
    pf.space_before = Pt(0)

    specs = {
        1: dict(size=15.0, bold=True,  italic=False, before=18, after=10, color=NAVY),
        2: dict(size=12.5, bold=True,  italic=False, before=14, after=4,  color=NAVY),
        3: dict(size=11.0, bold=True,  italic=True,  before=11, after=3,  color=NAVY),
        4: dict(size=10.5, bold=True,  italic=False, before=9,  after=2,  color=INK),
        5: dict(size=10.5, bold=True,  italic=True,  before=8,  after=2,  color=INK),
        6: dict(size=10.5, bold=False, italic=True,  before=8,  after=2,  color=INK),
    }
    for lvl, s in specs.items():
        st = doc.styles[f'Heading {lvl}']
        st.font.name      = BODY_FONT
        st.font.size      = Pt(s['size'])
        st.font.bold      = s['bold']
        st.font.italic    = s['italic']
        st.font.color.rgb = s['color']
        pf = st.paragraph_format
        pf.space_before   = Pt(s['before'])
        pf.space_after    = Pt(s['after'])
        pf.keep_with_next = True
        pf.alignment      = WD_ALIGN_PARAGRAPH.LEFT
        rPr = st.element.get_or_add_rPr()
        rf = rPr.find(qn('w:rFonts'))
        if rf is None:
            rf = OxmlElement('w:rFonts'); rPr.append(rf)
        for a in ('w:ascii', 'w:hAnsi', 'w:cs', 'w:eastAsia'):
            rf.set(qn(a), BODY_FONT)

    for name in ('List Bullet', 'List Bullet 2', 'List Bullet 3'):
        try:
            st = doc.styles[name]
            st.font.name = BODY_FONT
            st.font.size = BODY_SIZE
            st.font.color.rgb = INK
            st.paragraph_format.space_after  = Pt(2)
            st.paragraph_format.line_spacing = 1.15
        except KeyError:
            pass


