def _configure_table(table):
    tblPr = table._tbl.tblPr

    for el in tblPr.findall(qn('w:tblBorders')):
        tblPr.remove(el)
    for el in tblPr.findall(qn('w:tblCellMar')):
        tblPr.remove(el)

    w = OxmlElement('w:tblW')
    w.set(qn('w:w'), '5000'); w.set(qn('w:type'), 'pct')
    tblPr.insert_element_before(w, 'w:jc', 'w:tblCellSpacing', 'w:tblInd',
                                'w:tblBorders', 'w:shd', 'w:tblLayout',
                                'w:tblCellMar', 'w:tblLook', 'w:tblCaption',
                                'w:tblDescription', 'w:tblPrChange')

    b = OxmlElement('w:tblBorders')
    for edge in ('top', 'left', 'bottom', 'right', 'insideH', 'insideV'):
        e = OxmlElement(f'w:{edge}')
        e.set(qn('w:val'),   'single')
        e.set(qn('w:sz'),    '4')
        e.set(qn('w:space'), '0')
        e.set(qn('w:color'), RULE_GREY)
        b.append(e)
    tblPr.insert_element_before(b, 'w:shd', 'w:tblLayout', 'w:tblCellMar',
                                'w:tblLook', 'w:tblCaption',
                                'w:tblDescription', 'w:tblPrChange')

    mar = OxmlElement('w:tblCellMar')
    for name, v in (('top', 60), ('bottom', 60), ('left', 110), ('right', 110)):
        e = OxmlElement(f'w:{name}')
        e.set(qn('w:w'), str(v)); e.set(qn('w:type'), 'dxa')
        mar.append(e)
    tblPr.insert_element_before(mar, 'w:tblLook', 'w:tblCaption',
                                'w:tblDescription', 'w:tblPrChange')


def add_table(doc, rows):
    ncols = max(len(r) for r in rows)
    t = doc.add_table(rows=0, cols=ncols)
    t.autofit = True
    _configure_table(t)

    for r_i, row in enumerate(rows):
        cells = t.add_row().cells
        for c_i in range(ncols):
            val = row[c_i] if c_i < len(row) else ''
            p = cells[c_i].paragraphs[0]
            p.paragraph_format.space_after  = Pt(0)
            p.paragraph_format.space_before = Pt(0)
            p.paragraph_format.line_spacing = 1.0
            p.paragraph_format.alignment    = WD_ALIGN_PARAGRAPH.LEFT
            add_runs(p, val)
            if r_i == 0:
                _cell_shade(cells[c_i], HDR_FILL)
                for r_ in p.runs:
                    r_.bold = True
                    r_.font.color.rgb = NAVY
                for hl in p._p.findall(qn('w:hyperlink')):
                    for r_ in hl.findall(qn('w:r')):
                        rPr = r_.find(qn('w:rPr'))
                        if rPr is not None:
                            for c in rPr.findall(qn('w:color')):
                                c.set(qn('w:val'), '1A2E4A')
                            rPr.append(OxmlElement('w:b'))

    if len(t.rows):
        _repeat_header(t.rows[0])
    doc.add_paragraph()


