    configure_styles(doc)

    for section in doc.sections:
        section.top_margin      = MARGIN
        section.bottom_margin   = MARGIN
        section.left_margin     = MARGIN
        section.right_margin    = MARGIN
        section.header_distance = Inches(0.3)
        section.footer_distance = Inches(0.3)
        add_page_number_footer(section)

    lines = md_text.replace('\r\n', '\n').replace('\r', '\n').split('\n')
    i, title = 0, None

    while i < len(lines):
        raw = lines[i]
        s   = raw.strip()

        # --- fenced code block --------------------------------------
        if s.startswith('```'):
            i += 1
            buf = []
            while i < len(lines) and not lines[i].strip().startswith('```'):
                buf.append(lines[i]); i += 1
            i += 1
            for ln in buf:
                p = doc.add_paragraph()
                pf = p.paragraph_format
                pf.space_before = Pt(0); pf.space_after = Pt(0)
                pf.left_indent  = Inches(0.15)
                pf.right_indent = Inches(0.15)
                pf.line_spacing = 1.0
                pf.alignment    = WD_ALIGN_PARAGRAPH.LEFT
                shade(p, fill=CODE_FILL)
                r = p.add_run(ln if ln.strip() else ' ')
                r.font.name = MONO_FONT
                r.font.size = MONO_SIZE
                r.font.color.rgb = CODE_INK
            doc.add_paragraph()
            continue

        # --- display math  \[ .. \]  /  $$ .. $$ --------------------
        mo = DISPLAY_OPEN.match(s)
        if mo:
            body = s[mo.end():]
            while not DISPLAY_CLOSE.search(body) and i + 1 < len(lines):
                i += 1
                body += ' ' + lines[i].strip()
            body = DISPLAY_CLOSE.sub('', body).strip()
            if body:
                add_display_math(doc, body)
            i += 1
            continue

        # --- blank line / thematic break ----------------------------
        if not s or RULE_RE.match(s):
            i += 1
            continue

        # --- pipe table ---------------------------------------------
        if s.startswith('|') and i + 1 < len(lines) and \
                set(lines[i + 1].strip()) <= set('|-: '):
            rows = []
            while i < len(lines) and lines[i].strip().startswith('|'):
                cells = [c.strip() for c in
                         lines[i].strip().strip('|').split('|')]
                if not set(''.join(cells)) <= set('-: '):
                    rows.append(cells)
                i += 1
            if rows:
                add_table(doc, rows)
            continue

        # --- heading -------------------------------------------------
        m = HEADING_RE.match(s)
        if m:
            lvl, txt = len(m.group(1)), m.group(2)
            if lvl == 1 and title is None:
                title = txt
            h = doc.add_heading('', level=lvl)
            add_runs(h, txt)
            if lvl == 1:
                add_paragraph_border(h, edge='bottom', size=6,
                                     color='1A2E4A', space=6)
                h.paragraph_format.space_after = Pt(10)
            i += 1
            continue

        # --- task list -----------------------------------------------
        m = TASK_RE.match(s)
        if m:
            p = doc.add_paragraph(style='List Bullet')
            mark = p.add_run('☑  ' if m.group(1).lower() == 'x' else '☐  ')
            mark.font.color.rgb = NAVY
            add_runs(p, m.group(2))
            i += 1
            continue

        # --- blockquote ----------------------------------------------
        if s.startswith('>'):
            p = doc.add_paragraph()
            pf = p.paragraph_format
            pf.left_indent  = Inches(0.2)
            pf.right_indent = Inches(0.2)
            pf.space_before = Pt(4)
            pf.space_after  = Pt(6)
            add_paragraph_border(p, edge='left', size=18,
                                 color='9FB0C0', space=8)
            add_runs(p, re.sub(r'^>+\s?', '', s))
            for r_ in p.runs:
                r_.italic = True
                r_.font.color.rgb = SUBTLE
            i += 1
            continue

        # --- bullet list ---------------------------------------------
        m = BULLET_RE.match(raw)
        if m:
            ind = len(m.group(1))
            style = ('List Bullet' if ind < 2 else
                     'List Bullet 2' if ind < 4 else 'List Bullet 3')
            try:
                p = doc.add_paragraph(style=style)
            except KeyError:
                p = doc.add_paragraph()
            add_runs(p, m.group(2))
            i += 1
            continue

        # --- numbered list (numbers preserved) -----------------------
        m = NUMBER_RE.match(raw)
        if m:
            ind = 0 if len(m.group(1)) < 2 else (
                1 if len(m.group(1)) < 4 else 2)
            left = Inches(0.28 + 0.30 * ind)
            p = doc.add_paragraph()
            pf = p.paragraph_format
            pf.left_indent       = left
            pf.first_line_indent = -Inches(0.28)
            pf.space_after       = Pt(2)
            pf.line_spacing      = 1.15
            pf.alignment         = WD_ALIGN_PARAGRAPH.LEFT
            pf.tab_stops.add_tab_stop(left)
            r = p.add_run(f"{m.group(2)}.\t")
            r.font.color.rgb = NAVY
            add_runs(p, m.group(3))
            i += 1
            continue

        # --- normal paragraph ----------------------------------------
        add_runs(doc.add_paragraph(), s)
        i += 1

    return doc, title


