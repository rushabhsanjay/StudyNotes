def _border(edge, size=6, color=RULE_GREY, val='single', space=4):
    el = OxmlElement(f'w:{edge}')
    el.set(qn('w:val'),   val)
    el.set(qn('w:sz'),    str(size))
    el.set(qn('w:space'), str(space))
    el.set(qn('w:color'), color)
    return el


def add_paragraph_border(paragraph, edge='bottom', size=6,
                         color=RULE_GREY, space=4):
    pPr = paragraph._p.get_or_add_pPr()
    pBdr = pPr.find(qn('w:pBdr'))
    if pBdr is None:
        pBdr = OxmlElement('w:pBdr')
        pPr.insert_element_before(pBdr, *_PPR_AFTER_PBDR)
    pBdr.append(_border(edge, size=size, color=color, space=space))


def shade(obj, fill=CODE_FILL):
    """Background shading for a paragraph or a run, in schema order."""
    if hasattr(obj, '_p'):
        pr = obj._p.get_or_add_pPr()
        after = _PPR_AFTER_SHD
    else:
        pr = obj._r.get_or_add_rPr()
        after = _RPR_AFTER_SHD
    shd = OxmlElement('w:shd')
    shd.set(qn('w:val'),   'clear')
    shd.set(qn('w:color'), 'auto')
    shd.set(qn('w:fill'),  fill)
    pr.insert_element_before(shd, *after)


def _cell_shade(cell, fill):
    tcPr = cell._tc.get_or_add_tcPr()
    shd = OxmlElement('w:shd')
    shd.set(qn('w:val'),   'clear')
    shd.set(qn('w:color'), 'auto')
    shd.set(qn('w:fill'),  fill)
    tcPr.append(shd)


def _repeat_header(row):
    trPr = row._tr.get_or_add_trPr()
    el = OxmlElement('w:tblHeader')
    el.set(qn('w:val'), 'true')
    trPr.append(el)


