INLINE = re.compile(
    r'(\\{1,2}\(.+?\\{1,2}\)'             # \( inline math \)
    r'|\$(?!\s)[^$\n]*?[^\s$]\$(?!\$)'    # $inline math$
    r'|\*\*\*.+?\*\*\*'
    r'|\*\*.+?\*\*'
    r'|~~.+?~~'
    r'|\*[^*\n]+?\*'
    r'|`[^`\n]+`'
    r'|!\[[^\]]*\]\([^)]+\)'
    r'|\[[^\]]+\]\([^)]+\))'
)

_ESCAPED_OPEN  = re.compile(r'^\\{1,2}\(\s*')
_ESCAPED_CLOSE = re.compile(r'\s*\\{1,2}\)$')


def add_hyperlink(p, url, text):
    r_id = p.part.relate_to(
        url,
        "http://schemas.openxmlformats.org/officeDocument/2006/"
        "relationships/hyperlink",
        is_external=True)
    hl = OxmlElement('w:hyperlink'); hl.set(qn('r:id'), r_id)
    run = OxmlElement('w:r'); rPr = OxmlElement('w:rPr')
    rf = OxmlElement('w:rFonts')
    rf.set(qn('w:ascii'), BODY_FONT); rf.set(qn('w:hAnsi'), BODY_FONT)
    rPr.append(rf)
    c = OxmlElement('w:color'); c.set(qn('w:val'), '1A4E8A'); rPr.append(c)
    u = OxmlElement('w:u');    u.set(qn('w:val'), 'single'); rPr.append(u)
    run.append(rPr)
    t = OxmlElement('w:t'); t.set(qn('xml:space'), 'preserve'); t.text = text
    run.append(t); hl.append(run); p._p.append(hl)


def add_runs(p, text):
    for tok in INLINE.split(text):
        if not tok:
            continue

        # ---- math -------------------------------------------------
        if tok.startswith('\\') and _ESCAPED_CLOSE.search(tok):
            inner = _ESCAPED_CLOSE.sub('', _ESCAPED_OPEN.sub('', tok))
            add_inline_math(p, inner)

        elif len(tok) > 2 and tok.startswith('$') and tok.endswith('$'):
            add_inline_math(p, tok[1:-1])

        # ---- emphasis ---------------------------------------------
        elif tok.startswith('***') and tok.endswith('***'):
            r = p.add_run(tok[3:-3]); r.bold = True; r.italic = True
        elif tok.startswith('**') and tok.endswith('**'):
            p.add_run(tok[2:-2]).bold = True
        elif tok.startswith('~~') and tok.endswith('~~'):
            p.add_run(tok[2:-2]).font.strike = True
        elif (tok.startswith('*') and tok.endswith('*')
              and len(tok) > 2 and not tok.startswith('**')):
            p.add_run(tok[1:-1]).italic = True

        # ---- code span --------------------------------------------
        elif tok.startswith('`') and tok.endswith('`'):
            r = p.add_run(tok[1:-1])
            r.font.name = MONO_FONT
            r.font.size = Pt(9.5)
            r.font.color.rgb = RGBColor(0x33, 0x33, 0x33)
            shade(r, fill='EFEFEF')

        # ---- image placeholder ------------------------------------
        elif tok.startswith('!['):
            m = re.match(r'!\[([^\]]*)\]\(([^)]+)\)', tok)
            r = p.add_run(f"[image: {m.group(1) or m.group(2)}]")
            r.italic = True; r.font.color.rgb = SUBTLE

        # ---- link --------------------------------------------------
        elif tok.startswith('['):
            m = re.match(r'\[([^\]]+)\]\(([^)]+)\)', tok)
            add_hyperlink(p, m.group(2), m.group(1))

        else:
            p.add_run(tok)


