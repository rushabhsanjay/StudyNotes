def safe_filename(name):
    name = re.sub(r'[\\/:*?"<>|\r\n\t]+', ' ', name or '')
    name = re.sub(r'\s{2,}', ' ', name).strip(' .')
    return (name[:120] or 'Formatted Notes')


def _read_args_file():
    """Return (out_dir, base_name) from ARGS_FILE, or (None, None)."""
    if not os.path.isfile(ARGS_FILE):
        return None, None
    try:
        with open(ARGS_FILE, 'r', encoding='utf-8') as f:
            lines = [ln.rstrip('\r\n') for ln in f.readlines()]
    except Exception as e:
        print(f"WARNING: could not read args file: {e}")
        return None, None
    finally:
        try:
            os.remove(ARGS_FILE)
        except OSError:
            pass

    if len(lines) >= 2 and lines[0].strip():
        return lines[0].strip(), lines[1].strip()
    return None, None


def main():
    # ---- gather (out_dir, base_name) -------------------------------
    # Priority:
    #   1. command-line args  (manual CLI use)
    #   2. ARGS_FILE          (VBA writes it, we consume it)
    #   3. OUT_FILE fallback  (fixed scratch path)
    argv     = sys.argv[1:]
    cli_dir  = argv[0] if len(argv) >= 2 else None
    cli_name = argv[1] if len(argv) >= 2 else None

    if not (cli_dir and cli_name):
        file_dir, file_name = _read_args_file()
        if file_dir and file_name:
            cli_dir, cli_name = file_dir, file_name
            print(f"args file -> dir={cli_dir!r} name={cli_name!r}")

    text = pyperclip.paste()
    if not text or not text.strip():
        print("ERROR: Clipboard is empty.")
        sys.exit(4)

    text = clean_markdown(text)

    try:
        doc, title = build_document(text)
    except Exception:
        import traceback
        traceback.print_exc()
        print("ERROR during conversion.")
        sys.exit(5)

    # ---- decide where the DOCX goes --------------------------------
    if cli_dir and cli_name:
        # VBA's dynamic destination: <folder>\<TopicName>.docx
        base_name = cli_name
        out_dir   = os.path.normpath(cli_dir)
        out_path  = os.path.join(out_dir, base_name + ".docx")
    elif OUT_FILE:
        out_path  = OUT_FILE
        out_dir   = os.path.dirname(out_path) or OUT_DIR
        base_name = os.path.splitext(os.path.basename(out_path))[0]
    else:
        base_name = safe_filename(title or "Formatted Notes")
        out_dir   = OUT_DIR
        out_path  = os.path.join(out_dir, base_name + ".docx")

    print(f"DOCX -> {out_path}")
    os.makedirs(out_dir, exist_ok=True)

    doc.core_properties.title    = title or "Formatted Notes"
    doc.core_properties.comments = "Generated from clipboard markdown"

    try:
        doc.save(out_path)
    except Exception as e:
        print(f"ERROR saving DOCX: {e}")
        sys.exit(6)

    if not os.path.isfile(out_path):
        print("ERROR: Output file was not created.")
        sys.exit(7)

    print(f"OK -> {out_path}")
    if _XSLT is None:
        print("NOTE: MML2OMML.XSL not found or latex2mathml missing; "
              "equations were written as plain text.")
    elif _l2m is None:
        print("NOTE: latex2mathml not installed (pip install latex2mathml); "
              "equations were written as plain text.")

    # ---- companion HTML (best-effort, never fails the DOCX) --------
    if os.path.isfile(HTML_SCRIPT):
        html_path = os.path.join(out_dir, base_name + ".html")
        print(f"Generating HTML -> {html_path}")
        import subprocess
        try:
            r = subprocess.run(
                [sys.executable, HTML_SCRIPT, out_dir, base_name],
                check=False,
            )
            if r.returncode != 0:
                print(f"WARNING: HTML generator exited with code "
                      f"{r.returncode}")
        except Exception as e:
            print(f"WARNING: could not run HTML generator: {e}")
    else:
        print(f"NOTE: HTML companion not found at {HTML_SCRIPT}")


if __name__ == "__main__":
    main()