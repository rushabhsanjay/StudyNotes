def latex_fallback(src):
    """Turn LaTeX into something readable when no OMML pipeline exists."""
    s = src.strip()
    s = s.replace(r'\_', '_').replace(r'\%', '%').replace(r'\&', '&')

    for _ in range(8):                                   # nested \frac
        new = re.sub(r'\\frac\{([^{}]*)\}\{([^{}]*)\}', r'(\1)/(\2)', s)
        if new == s:
            break
        s = new

    s = re.sub(r'\\sqrt\{([^{}]*)\}', r'√(\1)', s)
    s = re.sub(r'\\(?:text|mathrm|mathbf|mathit|mathsf|mathtt|operatorname)'
               r'\{([^{}]*)\}', r'\1', s)
    for cmd, rep in _LATEX_MAP.items():
        s = s.replace(cmd, rep)
    s = re.sub(r'\\left|\\right|\\big|\\Big|\\bigg|\\Bigg', '', s)
    s = re.sub(r'\\[A-Za-z]+', '', s)                    # unknown commands
    s = s.replace('{', '').replace('}', '')
    s = s.replace('\\', '')
    return re.sub(r'\s{2,}', ' ', s).strip()


def latex_to_omml(latex, display=False):
    """LaTeX -> Word-native equation element, or None."""
    if _XSLT is None or _l2m is None:
        return None
    try:
        src = latex.strip()
        src = src.replace(r'\_', '_')
        src = re.sub(r'\\{1,2}([\[\]])', r'\1', src)      # stray delimiters
        mathml = _l2m.convert(src)
        root = _XSLT(etree.fromstring(mathml.encode('utf-8'))).getroot()
    except Exception:
        return None

    if root.tag == qn('m:oMathPara'):
        return root

    if root.tag == qn('m:oMath'):
        omath = root
    else:
        omath = root.find('.//' + qn('m:oMath'))
        if omath is None:
            return None

    if display:
        para = OxmlElement('m:oMathPara')
        para.append(omath)
        return para
    return omath


def add_inline_math(p, latex):
    el = latex_to_omml(latex, display=False)
    if el is None:
        r = p.add_run(latex_fallback(latex))
        r.italic = True
        r.font.name = BODY_FONT
    else:
        p._p.append(el)


def add_display_math(doc, latex):
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p.paragraph_format.space_before = Pt(6)
    p.paragraph_format.space_after = Pt(8)
    el = latex_to_omml(latex, display=True)
    if el is None:
        r = p.add_run(latex_fallback(latex))
        r.italic = True
        r.font.name = BODY_FONT
    else:
        p._p.append(el)
    return p


